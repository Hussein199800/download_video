// أقسام الشرح (في «المزيد ← المساعدة»)
export function guideList() {
  return h('ul', { class: 'guide' }, ITEMS.map(([color, icon, title, body]) => {
      const li = h('li', { class: 'g-item' },
        h('button', { class: 'g-head', 'aria-expanded': 'false', onclick: () => { li.classList.toggle('open'); li.firstChild.setAttribute('aria-expanded', String(li.classList.contains('open'))); } },
          ic(icon, `l-ic ${color}`), h('b', {}, title), ic('chevL', 'chev')),
        h('div', { class: 'g-body' }, body()));
      return li;
    }));
}
